/** The languages the interface has a full table for, in the order the toggle shows them. */
export const LANGS = ['en', 'es'];

let lang = 'en';
export function setLang(l) { if (STRINGS[l]) lang = l; }
export function getLang() { return lang; }

/** t('play.start') -> 'Start'. Missing keys return the key, loudly. */
export function t(path) {
  const v = path.split('.').reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), STRINGS[lang]);
  return v === undefined ? `[${path}]` : v;
}

/**
 * The name a player says out loud for a card, in the current language.
 *
 * No card face prints its name, so this is a spoken label and nothing else. In
 * English it is data/cards.json's own `name`, which is why there is no English
 * name table to drift from it; in another language it is the overlay in that
 * language's `cards.name`, keyed by card id, falling back to the English name
 * so an untranslated card is still readable rather than a raw [key].
 */
/**
 * The five boss reactions as an id-to-name map for the current language. A
 * table, not a string, so it does not go through t(): t() is contracted to
 * return a STRING and tests/content.test.mjs enforces that by scanning every
 * call, which is a contract worth keeping rather than widening.
 */
/**
 * The boss's atmospheric lines for the current language. A table, not a string,
 * so it does not go through t(): t() is contracted to return a STRING and
 * tests/content.test.mjs enforces that by scanning every call.
 */
export function bossLines() {
  return STRINGS[lang]?.play?.say || STRINGS.en.play.say;
}

export function reactionNames() {
  return { ...(STRINGS[lang]?.play?.reactionName || STRINGS.en.play.reactionName) };
}

/**
 * The Break Points aid draws its own labels, and js/cards/face.js is shared with
 * the print path and the node tests, neither of which sets a language. So the
 * names travel in through opts, the same way the boss reaction names already do.
 */
export function breakNames() {
  const b = STRINGS[lang]?.play?.brk || STRINGS.en.play.brk;
  return { wound: b.wound, cripple: b.cripple, trophy: b.trophy };
}
export function dmNames() {
  const d = STRINGS[lang]?.play?.dm || STRINGS.en.play.dm;
  return { friendly: d.friendly, assisted: d.assisted, hardcore: d.hardcore };
}

/**
 * An element's name in the reader's language. RULES.es.md has said Fuego, Agua,
 * Tierra and Viento since it was written; the screen said Fire, Water, Earth and
 * Wind, because seven render sites each capitalised the raw id instead of asking.
 */
export function elementName(el) {
  if (!el) return '';
  const table = STRINGS[lang]?.cards?.element || STRINGS.en.cards.element;
  return table[el] || (el.charAt(0).toUpperCase() + el.slice(1));
}

export function cardName(card) {
  if (!card) return '';
  const table = STRINGS[lang]?.cards?.name;
  return (card.id && table?.[card.id]) || card.name || '';
}
